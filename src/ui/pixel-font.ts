for (const [ch, rows] of Object.entries(FONT)) {
  if (rows.length !== 7) throw new Error(`font '${ch}' has ${rows.length} rows, expected 7`);
  for (const row of rows) {
    if (row.length !== 5) throw new Error(`font '${ch}' row "${row}" has ${row.length} chars, expected 5`);
  }
}

export function pixelTextWidth(text: string, scale: number): number {
  return Math.max(0, text.length * 6 * scale - scale);
}

export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 2,
): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const raw of text) {
    const glyph = FONT[raw] ?? FONT[raw.toUpperCase()] ?? FONT["?"]!;
    for (let row = 0; row < glyph.length; row++) {
      const line = glyph[row]!;
      for (let col = 0; col < line.length; col++) {
        if (line[col] === "#") ctx.fillRect(cx + col * scale, y + row * scale, scale, scale);
      }
    }
    cx += 6 * scale;
  }
}

export function drawPixelTextCenter(
  ctx: CanvasRenderingContext2D,
  text: string,
  centerX: number,
  y: number,
  color: string,
  scale = 2,
): void {
  drawPixelText(ctx, text, Math.round(centerX - pixelTextWidth(text, scale) / 2), y, color, scale);
}

export function wrapPixelText(text: string, maxWidth: number, scale: number): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  if (words.length === 0) return [""];
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word;
    if (!line || pixelTextWidth(candidate, scale) <= maxWidth) {
      line = candidate;
    } else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

export function drawPixelTextRight(
  ctx: CanvasRenderingContext2D,
  text: string,
  rightX: number,
  y: number,
  color: string,
  scale = 2,
): void {
  drawPixelText(ctx, text, rightX - pixelTextWidth(text, scale), y, color, scale);
}
